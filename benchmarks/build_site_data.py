"""Write site/data.js from the saved results, so that every number on the site comes from a result file.

    python benchmarks/build_site_data.py
"""
import os, json
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
R = lambda *p: json.load(open(os.path.join(ROOT, *p)))
MODELS = [("lifelib_savings", "Savings", "CashValue_ME"), ("lifelib_savings_dynamic", "Savings, dynamic lapse", "CashValue_ME_EX2"),
          ("lifelib_basicterm", "Term assurance", "BasicTerm_ME"), ("lifelib_fastlife", "Traditional life, annual", "fastlife")]
STEPS = [("cpu 1 core, float64, no early exit", "Compiled, one core"), ("cpu all cores, float64, no early exit", "All 20 processor cores"),
         ("cpu all cores, float64", "Stop when nothing is left"), ("gpu, float64", "Graphics processor, 16 digits"),
         ("gpu, float32", "Graphics processor, 7 digits")]
t = R("benchmarks", "results", "timings.json"); c = R("benchmarks", "results", "certify.json")
# one policy at a time (lifelib's unvectorised siblings), seconds per million rows
sav = R("examples", "lifelib_savings", "results", "baseline.json")
one = {"lifelib_savings": sav["seconds_one_at_a_time"] / sav["policies"] * 1e6,
       "lifelib_basicterm": R("examples", "lifelib_basicterm", "results", "baseline.json")["timing"]["seconds_per_policy"] * 1e6,
       "lifelib_fastlife": R("examples", "lifelib_fastlife", "results", "baseline.json")["timing"]["seconds_per_policy"] * 1e6}
out = {"machine": t["machine"], "models": []}
for key, name, lib in MODELS:
    m = t[key]; ks = m["kernel_seconds_per_million_rows"]
    steps = ([{"label": "One policy at a time", "s": one[key], "kind": "original"}] if key in one else [])
    steps += [{"label": "Vectorised (as lifelib ships it)", "s": m["original"]["seconds_per_million_rows"], "kind": "original"}]
    steps += [{"label": lab, "s": ks[k], "kind": "kernel"} for k, lab in STEPS]
    harness = R("examples", key, "results", "harness.json")
    if key == "lifelib_savings_dynamic":
        tab = None
    else:
        tab = [{"check": a, "caught": b, "of": n} for a, b, n in harness["table"]]
    cert = c[key]
    out["models"].append({"key": key, "name": name, "lib": lib, "period": m["period"], "periods": m["periods_per_row"], "steps": steps,
                          "defects": tab, "certify": {"rows": cert["rows"], "certified": cert["rows_certified"],
                          "width_median": cert["enclosure_width"]["median"],
                          "variants": {v: {"worst": r["distance_from_exact"]["worst"], "median": r["distance_from_exact"]["median"],
                                           "net_worst": r["net_cashflow_distance_from_exact"]["worst"]} for v, r in cert["variants"].items()}}})
dyn = R("examples", "lifelib_savings_dynamic", "results", "harness.json")["defects/dynamic"]
out["models"][1]["defects"] = [{"check": a, "caught": b, "of": n} for a, b, n in dyn["table"]]
open(os.path.join(ROOT, "site", "data.js"), "w").write("// generated by benchmarks/build_site_data.py\nwindow.EXA = " + json.dumps(out, indent=1) + ";\n")
print("wrote site/data.js")
